"""
Validation-only weight tuning for the AstroTrust-AI early-aware partial ensemble.

Goal
----
Tune the partial-light-curve ensemble weights without using the final evaluation
subset.

The script uses the existing member probabilities generated by:
  results/broker_like_stage_aware_ensemble/

It splits held-out object IDs into:
  1) weight_validation_subset: used only to choose weights;
  2) final_test_subset: used only once after weights are frozen.

This avoids choosing weights directly on the final test subset.

Default members:
  hybrid_early_aware
  lightgbm_early_aware
  lightgbm_regularized_early_aware
  xgboost_early_aware

Default fixed baseline weights:
  0.70, 0.15, 0.10, 0.05

Recommended run:
  python .\experiments\tune_stage_aware_early_aware_weights.py `
    --input-dir results\broker_like_stage_aware_ensemble `
    --output-dir results\broker_like_stage_aware_weight_tuning `
    --grid-step 0.05 `
    --n-bootstrap 1000 `
    --log-every 100

Outputs:
  tuned_weights.json
  tuned_weight_grid_scores.csv
  tuned_stage_aware_point_metrics.csv
  tuned_stage_aware_paired_bootstrap.csv
  tuned_stage_aware_mcnemar.csv
  tuned_stage_aware_followup_bootstrap.csv
  tuned_stage_aware_weight_tuning_summary.md
"""

